from pathlib import Path
from typing import Any, Dict, List, Tuple

import adif_io


QSLMASTER_PROGRAM_ID = 'QSLMaster'


class ADIFFileError(Exception):
    pass


def parse_adif_document(adif_content: str) -> Tuple[List[Dict[str, Any]], Dict[str, Any]]:
    if '<EOH>' not in adif_content.upper():
        adif_content = adif_content.lstrip()
    try:
        return adif_io.read_from_string(adif_content)
    except Exception as e:
        raise ADIFFileError(f"ADIF parsing error: {e}")


def parse_adif_content(adif_content: str) -> List[Dict[str, Any]]:
    return parse_adif_document(adif_content)[0]


def load_adif_file(adif_file_path: str) -> str:
    path = Path(str(adif_file_path).strip())
    if not path.exists() or not path.is_file():
        raise ADIFFileError(f"ADIF file does not exist or is not a file: {adif_file_path}")
    try:
        return path.read_text(encoding='utf-8')
    except Exception as e:
        raise ADIFFileError(f"Failed to read ADIF file {adif_file_path}: {e}")


def load_qsos_from_adif_file(adif_file_path: str) -> List[Dict[str, Any]]:
    return parse_adif_content(load_adif_file(adif_file_path))


def load_qslmaster_output_file(adif_file_path: str) -> List[Dict[str, Any]]:
    qsos, headers = parse_adif_document(load_adif_file(adif_file_path))
    if str(headers.get('PROGRAMID', '') or '').strip() != QSLMASTER_PROGRAM_ID:
        raise ADIFFileError(f"{adif_file_path} is not a QSLMaster output file. Use the ADIF file created by QSLMaster processing")
    return qsos


def write_adif_file(adif_file_path: str, qsos: List[Dict[str, Any]]) -> None:
    with open(adif_file_path, 'w', encoding='UTF-8') as file_handle:
        file_handle.write("ADI file generated by QSLMaster\n")
        file_handle.write(" <ADIF_VER:5>3.1.6")
        file_handle.write(f" <PROGRAMID:{len(QSLMASTER_PROGRAM_ID)}>{QSLMASTER_PROGRAM_ID}")
        file_handle.write(" <EOH>\n")
        for qso in qsos:
            file_handle.write(adif_io.qso_to_adif(qso))
