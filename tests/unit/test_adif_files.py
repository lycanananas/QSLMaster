import pytest

from qslmaster_cli.adif_files import ADIFFileError, load_qsos_from_adif_file, parse_adif_content, write_adif_file


def test_parse_records_without_header_and_leading_whitespace():
    qsos = parse_adif_content('\n<CALL:5>SP5AA <EOR>\n<CALL:5>SP5AB <EOR>\n')
    assert [qso['CALL'] for qso in qsos] == ['SP5AA', 'SP5AB']


def test_write_and_load_round_trip(tmp_path):
    path = tmp_path / 'out.adi'
    write_adif_file(str(path), [{'CALL': 'SP5AA', 'QSL_SENT': 'Y', 'QSL_SENT_VIA': 'B', 'QSL_VIA': 'OT-25'}])
    assert path.read_text(encoding='utf-8').startswith('ADI file generated by QSLMaster')
    qsos = load_qsos_from_adif_file(str(path))
    assert qsos[0]['QSL_VIA'] == 'OT-25'


def test_missing_file_raises(tmp_path):
    with pytest.raises(ADIFFileError):
        load_qsos_from_adif_file(str(tmp_path / 'missing.adi'))


def test_mark_sent_input_must_be_qslmaster_output(tmp_path):
    from qslmaster_cli.adif_files import load_qslmaster_output_file
    own = tmp_path / 'own.adi'
    write_adif_file(str(own), [{'CALL': 'SP5AA', 'QSL_SENT': 'Y'}])
    assert [qso['CALL'] for qso in load_qslmaster_output_file(str(own))] == ['SP5AA']

    foreign = tmp_path / 'wavelog_export.adi'
    foreign.write_text('Wavelog export <PROGRAMID:7>Wavelog <EOH>\n<CALL:5>SP5AA <QSL_SENT:1>Y <EOR>\n', encoding='utf-8')
    with pytest.raises(ADIFFileError, match='not a QSLMaster output file'):
        load_qslmaster_output_file(str(foreign))
